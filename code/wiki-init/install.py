_PY_KEY = re.compile(r"([\w-]+\.py)")


def fail(code: int, msg: str):
    print(f"wiki-init install: {msg}", file=sys.stderr)
    sys.exit(code)


def _git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(("git",) + args, cwd=root, capture_output=True, text=True)


def precheck_precommit(root: Path):
    """Refuse before template writes if activating managed hooks would disable foreign policy."""
    if _git(root, "diff", "--cached", "--quiet").returncode != 0:
        fail(3, "Git index contains staged changes; preserve/commit them before installation or update")
    git_dir = Path(_git(root, "rev-parse", "--absolute-git-dir").stdout.strip())
    if (git_dir / "wiki-checkpoint-txn").exists() or (git_dir / "wiki-background/active").exists():
        fail(3, "unfinished checkpoint transaction or background job; finish/recover/cancel it before changing runtime tooling")
    configured = _git(root, "config", "--local", "--get", "core.hooksPath")
    current = configured.stdout.strip() if configured.returncode == 0 else ""
    if current:
        if current.replace("\\", "/").rstrip("/") == MANAGED_HOOKS_PATH:
            return
        checker = root / ".memory/tools/install_hooks.py"
        if checker.is_file():
            health = subprocess.run((sys.executable, str(checker), "--check"), cwd=root,
                                    capture_output=True, text=True,
                                    env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"})
            if health.returncode == 0:
                return
        fail(3, f"foreign or unhealthy core.hooksPath `{current}` — refusing to overwrite it")
    hooks_path = _git(root, "rev-parse", "--git-path", "hooks")
    if hooks_path.returncode != 0:
        fail(2, f"cannot resolve hooks path: {hooks_path.stderr}")
    hooks_dir = Path(hooks_path.stdout.strip())
    if not hooks_dir.is_absolute():
        hooks_dir = root / hooks_dir
    for hook in sorted(hooks_dir.iterdir()) if hooks_dir.is_dir() else []:
        if hook.name.endswith(".sample") or not hook.is_file():
            continue
        if hook.name == "pre-commit":
            text = hook.read_text(encoding="utf-8").replace("\r\n", "\n")
            if text == LEGACY_OWNED_HOOK:
                continue
        fail(3, f"existing hook `{hook}` is foreign — core.hooksPath would disable it")


def prechecks(root: Path, codex: bool, prime: bool = False, claude: bool = True):
    r = _git(root, "rev-parse", "--is-inside-work-tree")
    if r.returncode != 0 or r.stdout.strip() != "true":
        fail(2, f"{root} is not a git repo — the checkpoint commands detect the last "
                "checkpoint via git. Run `git init` first, then rerun.")
    precheck_precommit(root)
    collisions = []
    if (root / ".memory").exists():
        collisions.append(".memory/")
    cmd_dir = root / ".claude" / "commands"
    if claude and cmd_dir.is_dir():
        collisions += sorted(f".claude/commands/{p.name}" for p in cmd_dir.glob("wiki-*.md"))
    cm = root / "CLAUDE.md"
    if claude and cm.is_file() and "# Session Memory" in cm.read_text(encoding="utf-8"):
        collisions.append("CLAUDE.md: existing '# Session Memory' block")
    if codex:
        for rel in (".codex", ".agents", "AGENTS.md"):
            if (root / rel).exists():
                collisions.append(f"{rel} (--codex would overwrite it)")
    if prime:
        for src in sorted(PRIME_TREE.rglob("*")):
            if src.is_file():
                rel = src.relative_to(PRIME_TREE).as_posix()
                if (root / rel).exists():
                    collisions.append(f"{rel} (--prime would overwrite it)")
    if collisions:
        fail(3, "collision — this protects real memory, NOTHING was created:\n  "
                + "\n  ".join(collisions))


def entry_key(entry: dict) -> str:
    """Merge key for a hook entry = the script filename its command references.
    A legacy `rtk.exe hook claude` registration keys as rtk_deny_net.py — both are
    RETIRED now, and update.py strips them by that key (rtk dropped, decision 0047)."""
    cmds = " ".join(h.get("command", "") for h in entry.get("hooks", []))
    m = _PY_KEY.search(cmds)
    if m:
        return m.group(1)
    if "rtk.exe" in cmds:
        return "rtk_deny_net.py"
    return cmds


def _write(path: Path, content: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)


def install_tree(root: Path, project: str, neutral: bool = False) -> list[str]:
    created = []
    for src in sorted(TREE.rglob("*")):
        if src.is_dir() or "__pycache__" in src.parts or src.suffix == ".pyc":
            continue
        rel = src.relative_to(TREE).as_posix()
        if neutral and rel.startswith(".claude/commands/"):
            rel = rel.replace(".claude/commands/", ".memory/commands/", 1)
        content = src.read_text(encoding="utf-8")
        if src.suffix == ".md":  # <project> lives only in md templates; code copies byte-exact
            content = content.replace("<project>", project)
            if neutral:
                content = content.replace("`CLAUDE.md`", "`.memory/INSTRUCTIONS.md`")
        _write(root / rel, content)
        created.append(rel)
    for rel in (".memory/wiki/concepts/.gitkeep", ".memory/wiki/decisions/.gitkeep",
                "code/.gitkeep"):
        _write(root / rel, "")
        created.append(rel)
    return created


def install_codex(root: Path, project: str) -> list[str]:
    """Copy the Codex layer: .codex/ hooks (absolute commandWindows paths) + static
    skill metadata. AGENTS.md / SKILL.md are NOT copied here — dual_sync.py generates
    them. Hooks stay dormant until the user accepts Codex's hook-trust prompt (see
    module docstring)."""
    created = []
    repo_win = json.dumps(str(root))[1:-1]  # JSON-escaped absolute path
    for src in sorted(CODEX_TREE.rglob("*")):
        if src.is_dir():
            continue
        rel = src.relative_to(CODEX_TREE).as_posix()
        content = (src.read_text(encoding="utf-8")
                   .replace("<repoWin>", repo_win).replace("<project>", project))
        _write(root / rel, content)
        created.append(rel)
    return created


def merge_prime_settings(root: Path) -> str:
    """Install the Prime compaction floor without clobbering user project settings.

    WikiInit owns only missing keys under `compaction`; an explicit project choice stays
    authoritative. Unrelated Prime settings and resources are never changed.
    """
    tpl = json.loads(PRIME_SETTINGS_TPL.read_text(encoding="utf-8"))
    dst = root / ".prime" / "agent" / "settings.json"
    if not dst.exists():
        _write(dst, json.dumps(tpl, indent=2) + "\n")
        return "written verbatim (no existing Prime project settings)"
    try:
        cfg = json.loads(dst.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        fail(3, f"cannot merge {dst.relative_to(root).as_posix()}: {exc}")
    if not isinstance(cfg, dict):
        fail(3, f"cannot merge {dst.relative_to(root).as_posix()}: JSON root must be an object")
    compaction = cfg.setdefault("compaction", {})
    if not isinstance(compaction, dict):
        fail(3, ".prime/agent/settings.json: compaction must be an object")
    for key, value in tpl["compaction"].items():
        compaction.setdefault(key, value)
    _write(dst, json.dumps(cfg, indent=2) + "\n")
    return "MERGED missing compaction keys (existing choices + unrelated settings preserved)"


def install_prime(root: Path, project: str) -> list[str]:
    """Copy WikiInit-owned Prime resources and merge the project compaction floor.

    The adapter discovers shared .memory/commands (or legacy .claude/commands),
    so those command bodies remain the single source of truth. Existing unrelated
    .prime/agent settings, skills, prompts, and extensions are never touched.
    """
    created = []
    for src in sorted(PRIME_TREE.rglob("*")):
        if src.is_dir():
            continue
        rel = src.relative_to(PRIME_TREE).as_posix()
        content = src.read_text(encoding="utf-8").replace("<project>", project)
        _write(root / rel, content)
        created.append(rel)
    merge_prime_settings(root)
    created.append(".prime/agent/settings.json")
    return created


def run_dual_sync(root: Path) -> list[str]:
    r = subprocess.run([sys.executable, ".memory/tools/dual_sync.py"],
                       cwd=root, capture_output=True, text=True)
    if r.returncode != 0:
        fail(5, f"dual_sync failed:\n{r.stdout}{r.stderr}")
    return [Path(ln[len("synced: "):]).as_posix() for ln in r.stdout.splitlines()
            if ln.startswith("synced: ")]


def _make_executable(path: Path):
    """Set executable bits on POSIX; harmless on filesystems that ignore modes."""
    mode = path.stat().st_mode
    path.chmod(mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


def install_precommit(root: Path) -> str:
    """Activate the tracked hook; never overwrite/chase a foreign hooksPath."""
    bootstrap = root / ".memory" / "tools" / "install_hooks.py"
    r = subprocess.run((sys.executable, str(bootstrap)), cwd=root,
                       capture_output=True, text=True,
                       env={**os.environ, "PYTHONDONTWRITEBYTECODE": "1"})
    if r.returncode != 0:
        fail(3, "managed pre-commit bootstrap refused:\n" + (r.stderr or r.stdout))
    return r.stdout.strip()


def merge_settings(root: Path) -> str:
    tpl = json.loads(SETTINGS_TPL.read_text(encoding="utf-8"))
    dst = root / ".claude" / "settings.json"
    if not dst.exists():
        _write(dst, json.dumps(tpl, indent=2) + "\n")
        return "written verbatim (no existing settings.json)"
    cfg = json.loads(dst.read_text(encoding="utf-8"))
    hooks = cfg.setdefault("hooks", {})
    for event, entries in tpl["hooks"].items():
        arr = hooks.setdefault(event, [])
        for te in entries:
            key = entry_key(te)
            for i, existing in enumerate(arr):
                if entry_key(existing) == key:
                    arr[i] = te  # upgrade in place, never duplicate
                    break
            else:
                arr.append(te)
    allow = cfg.setdefault("permissions", {}).setdefault("allow", [])
    for a in tpl["permissions"]["allow"]:
        if a not in allow:
            allow.append(a)
    _write(dst, json.dumps(cfg, indent=2) + "\n")
    return "MERGED into existing (hooks upserted by key, allows unioned, rest untouched)"


def claude_md(root: Path, project: str) -> str:
    frag = (FRAGS / "claude-md-memory.md").read_text(encoding="utf-8") \
        .replace("<project>", project)
    cm = root / "CLAUDE.md"
    if cm.exists():
        cur = cm.read_text(encoding="utf-8")
        sep = "\n" if cur.endswith("\n") else "\n\n"
        _write(cm, cur + sep + frag)
        return "APPENDED memory section to existing CLAUDE.md"
    _write(cm, frag)
    return "created with memory section"


def commit(root: Path, paths: list[str]):
    r = _git(root, "add", "--", *paths)
    if r.returncode != 0:
        fail(5, f"git add failed:\n{r.stderr}")
    r = _git(root, "commit", "-m", "chore: install wiki+STATE session memory (/wiki-init)")
    if r.returncode != 0:
        fail(5, "git commit failed (files ARE installed — fix the cause, e.g. git "
                f"user.name/email, then commit manually):\n{r.stderr}")
    return _git(root, "rev-parse", "--short", "HEAD").stdout.strip()



def watchdog_plan(root: Path, requested: bool, codex: bool):
    """Read-only deployment preflight before template writes or installation commit."""
    if requested and not codex:
        fail(3, "--watchdog requires an enabled Codex runtime (--codex)")
    git_dir = Path(_git(root, "rev-parse", "--absolute-git-dir").stdout.strip())
    registered = (git_dir / "wiki-background-monitor/registration.json").exists()
    action = "install" if requested else "refresh" if registered else None
    if action:
        probe = subprocess.run([sys.executable, str(TREE / ".memory/tools/checkpoint_watchdog.py"),
                                "--root", str(root), "preflight"], cwd=root,
                               capture_output=True, text=True)
        if probe.returncode:
            fail(3, "watchdog preflight refused before project writes:\n" + probe.stdout + probe.stderr)
    return action


def deploy_watchdog(root: Path, action, codex: bool):
    if not action:
        if codex:
            print("  note: watchdog not activated; checkpoint remains foreground. Use wiki-update --watchdog to enable supervised native background forks.")
        return
    result = subprocess.run([sys.executable, str(root / ".memory/tools/checkpoint_watchdog.py"),
                             "--root", str(root), action], cwd=root, capture_output=True, text=True)
    if result.returncode:
        fail(6, "tooling is installed, but watchdog deployment failed; background mode is NOT ready. "
                "Fix the reported problem and rerun wiki-update --watchdog (or rerun without it to preserve an existing stopped timer):\n"
                + result.stdout + result.stderr)
    print("  note: watchdog " + action + " completed:\n" + result.stdout.strip())


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("project", help="project name substituted for <project> in templates")
    ap.add_argument("--root", default=".", help="target repo root (default: cwd)")
    for runtime in ("claude", "codex", "prime"):
        ap.add_argument(f"--{runtime}", action=argparse.BooleanOptionalAction,
                        default=False, help=f"install the {runtime} runtime layer (default: off)")
    ap.add_argument("--watchdog", action="store_true", help="activate supervised background checkpoints (Codex + Linux user systemd required)")
    ap.add_argument("--portable", action="store_true", help="verify distribution files without requiring the Prime CLI; for CI, not live runtime readiness")
    args = ap.parse_args()
    root = Path(args.root).resolve()

    prechecks(root, args.codex, args.prime, args.claude)
    watchdog_action = watchdog_plan(root, args.watchdog, args.codex)

    created = install_tree(root, args.project, neutral=True)
    runtimes = {name: getattr(args, name) for name in ("claude", "codex", "prime")}
    _write(root / ".memory/runtimes.json", json.dumps(runtimes, indent=2) + "\n")
    instructions = (FRAGS / "claude-md-memory.md").read_text(encoding="utf-8").replace("<project>", args.project)
    if args.claude and (root / "CLAUDE.md").is_file():
        instructions = (root / "CLAUDE.md").read_text(encoding="utf-8").rstrip() + "\n\n" + instructions
    _write(root / ".memory/INSTRUCTIONS.md", instructions)
    created += [".memory/runtimes.json", ".memory/INSTRUCTIONS.md"]
    settings_note = merge_settings(root) if args.claude else None
    if args.claude:
        created.append(".claude/settings.json")
    if args.codex:
        created += install_codex(root, args.project)
    created += run_dual_sync(root)
    if args.prime:
        created += install_prime(root, args.project)

    # The isolated hook is built from committed HEAD bytes.  A fresh installation has
    # no memory runtime in HEAD until the bootstrap commit lands, so activate it afterwards.
    sha = commit(root, created)
    precommit_note = install_precommit(root)

    print(f"wiki-init: installed into {root} (project: {args.project}, "
          f"claude: {'yes' if args.claude else 'no'}, "
          f"codex: {'yes' if args.codex else 'no'}, "
          f"prime: {'yes' if args.prime else 'no'})")
    for rel in created:
        note = {".claude/settings.json": settings_note}.get(rel)
        print(f"  {rel} — {note or ROLES.get(rel, '')}")
    print(f"  .memory/hooks/pre-commit — {precommit_note}")
    print(f"  commit: {sha}")
    if args.codex:
        print("\nCodex hook trust (MANUAL, once): open this repo in Codex and accept the "
              "hook-trust prompt — untrusted hook entries are silently skipped until then.")
    if args.prime:
        print("\nPrime Agent: open the repo in a fresh Prime session (or run /reload in an "
              "existing one); /wiki-resume, /wiki-checkpoint and /wiki-clear are provided "
              "from the shared memory command sources.")

    print("\ndoctor (contour self-check):")
    r = subprocess.run([sys.executable, ".memory/tools/structural.py", "doctor", *(["--portable"] if args.portable else [])],
                       cwd=root, capture_output=True, text=True)
    out = (r.stdout + r.stderr).strip()
    print("  " + "\n  ".join(out.splitlines()))
    if r.returncode != 0:
        fail(4, "doctor FAILED — the contour is not alive on this machine; fix before "
                "declaring the install done.")
    deploy_watchdog(root, watchdog_action, args.codex)


if __name__ == "__main__":
    main()
