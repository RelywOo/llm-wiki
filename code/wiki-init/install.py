#!/usr/bin/env python3
"""wiki-init installer — deterministic scaffold of the wiki+STATE session-memory system.

Replaces the LLM retyping ~2000 template lines (10 min, drift-prone) with a mechanical
copy (~1 s, byte-exact). The /wiki-init command runs this and relays the report; judgment
(project name, collision resolution) stays with the model, bytes stay with the script.

Templates live in templates/ next to this file:
  tree/       — verbatim copies mirroring the destination layout (<project> substituted)
  settings.json — MERGED into an existing .claude/settings.json (upsert by script-filename
                  key, permissions.allow unioned), written verbatim when absent
  fragments/  — CLAUDE.md sections (memory), appended or used to create CLAUDE.md

All integrations default to off. --claude, --codex, and --prime independently
enable a runtime; --no-claude, --no-codex, and --no-prime explicitly disable it.
Shared instructions, commands, and runtime selections live in .memory/.
--claude adds Claude settings and generated commands/instructions.

With --codex the Codex layer is added: .codex/ project hooks
(commandWindows rendered with the ABSOLUTE repo path, mirroring the reference setup),
.agents/skills/ Codex skills, and AGENTS.md — the last two GENERATED by
.memory/tools/dual_sync.py from shared memory sources, never hand-kept.

With --prime a project-local Prime Agent adapter is added under .prime/agent/extensions/,
its compaction floor is merged into .prime/agent/settings.json, and a deterministic adapter
self-check is added under .memory/tools/. It exposes shared command sources as
native Prime prompt commands and maps Prime lifecycle events onto the same project-local memory contour. The wiki/STATE data
and shared commands remain the single source of truth; no second memory store is created.

The pre-commit guard (installed always) blocks any commit where dual artifacts drift.

Codex hook TRUST (observed live on 0.144): Codex pins a per-entry trusted_hash in
~/.codex/config.toml [hooks.state] and SILENTLY SKIPS any hook entry it does not
trust yet (headless exec included). One manual step after install: open the repo in
Codex (Desktop/interactive) once and accept the hook-trust prompt. This script never
writes [hooks.state] — the hash formula is app-internal.

Usage: python install.py <project-name> [--root DIR] [--claude] [--codex] [--prime]
Exit:  0 ok · 2 not a git repo · 3 collision/preflight · 4 doctor failed · 5 commit failed · 6 watchdog deployment failed
"""
